/**
 * Draws the stylized player avatar head onto a Canvas2D context at (x, y)
 */
export function drawPlayerAvatar(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  radius: number,
  angle: number,
  skin: SkinDefinition,
  isCrownLeader: boolean = false
) {
  ctx.save();
  ctx.translate(x, y);

  // Drop shadow
  ctx.save();
  ctx.beginPath();
  ctx.ellipse(0, radius * 0.4, radius * 0.95, radius * 0.6, 0, 0, Math.PI * 2);
  ctx.fillStyle = 'rgba(0, 0, 0, 0.18)';
  ctx.fill();
  ctx.restore();

  ctx.rotate(angle);

  const size = radius * 1.7;
  const half = size / 2;
  const round = radius * 0.45;

  // Darker bevel border
  ctx.beginPath();
  ctx.roundRect(-half - 1.5, -half - 1.5, size + 3, size + 3, round + 1);
  ctx.fillStyle = skin.secondaryColor;
  ctx.fill();

  // Main body fill
  ctx.beginPath();
  ctx.roundRect(-half, -half, size, size, round);
  ctx.fillStyle = skin.primaryColor;
  ctx.fill();

  // Highlight gradient
  const grad = ctx.createLinearGradient(-half, -half, half, half);
  grad.addColorStop(0, 'rgba(255, 255, 255, 0.35)');
  grad.addColorStop(0.5, 'rgba(255, 255, 255, 0.05)');
  grad.addColorStop(1, 'rgba(0, 0, 0, 0.2)');
  ctx.beginPath();
  ctx.roundRect(-half, -half, size, size, round);
  ctx.fillStyle = grad;
  ctx.fill();

  // Draw Eyes
  drawEyes(ctx, skin.eyeType, half, radius);

  // Crown
  if (skin.accessory === 'crown' || isCrownLeader) {
    drawCrown(ctx, -half * 0.1, 0, radius);
  }

  ctx.restore();
}

function drawEyes(
  ctx: CanvasRenderingContext2D,
  type: SkinDefinition['eyeType'],
  half: number,
  radius: number
) {
  const eyeForwardX = half * 0.35;
  const eyeSpreadY = half * 0.38;
  const eyeR = radius * 0.22;

  if (type === 'cyclops') {
    ctx.beginPath();
    ctx.arc(eyeForwardX + 2, 0, eyeR * 1.4, 0, Math.PI * 2);
    ctx.fillStyle = '#ffffff';
    ctx.fill();

    ctx.beginPath();
    ctx.arc(eyeForwardX + 4, 0, eyeR * 0.7, 0, Math.PI * 2);
    ctx.fillStyle = '#111827';
    ctx.fill();
    return;
  }

  const eyes = [
    { x: eyeForwardX, y: -eyeSpreadY },
    { x: eyeForwardX, y: eyeSpreadY },
  ];

  eyes.forEach(eye => {
    ctx.beginPath();
    ctx.arc(eye.x, eye.y, eyeR, 0, Math.PI * 2);
    ctx.fillStyle = '#ffffff';
    ctx.fill();

    ctx.beginPath();
    ctx.arc(eye.x + eyeR * 0.3, eye.y, eyeR * 0.55, 0, Math.PI * 2);
    ctx.fillStyle = '#111827';
    ctx.fill();

    ctx.beginPath();
    ctx.arc(eye.x + eyeR * 0.45, eye.y - eyeR * 0.2, eyeR * 0.2, 0, Math.PI * 2);
    ctx.fillStyle = '#ffffff';
    ctx.fill();
  });
}

function drawCrown(
  ctx: CanvasRenderingContext2D,
  cx: number,
  cy: number,
  radius: number
) {
  ctx.save();
  ctx.translate(cx, cy);

  const crownW = radius * 0.9;
  const crownH = radius * 0.65;

  ctx.beginPath();
  ctx.moveTo(-crownH, -crownW / 2);
  ctx.lineTo(-crownH * 0.4, -crownW / 3);
  ctx.lineTo(-crownH * 1.1, 0);
  ctx.lineTo(-crownH * 0.4, crownW / 3);
  ctx.lineTo(-crownH, crownW / 2);
  ctx.lineTo(-crownH * 0.2, crownW / 2);
  ctx.lineTo(-crownH * 0.2, -crownW / 2);
  ctx.closePath();

  ctx.fillStyle = '#ffd100';
  ctx.shadowColor = 'rgba(255, 209, 0, 0.6)';
  ctx.shadowBlur = 6;
  ctx.fill();

  ctx.lineWidth = 1.5;
  ctx.strokeStyle = '#d4a017';
  ctx.stroke();

  ctx.restore();
}
